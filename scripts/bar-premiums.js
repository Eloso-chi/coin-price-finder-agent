#!/usr/bin/env node
/**
 * bar-premiums.js (#333H phase 3)
 *
 * Builds data/bar-premiums.json from the bar datasets in data/terapeak: per
 * segment (metal, weight bucket, series / brand / generic) the sold-price and
 * premium-over-spot statistics, plus the brand-over-generic price ratio.
 *
 * Premium over spot needs spot history. Pass --metals-history FILE (the
 * metals_history.json the server records, { XAG: { 'YYYY-MM-DD': price } });
 * without it the premium fields are null and only prices and ratios are filled.
 * Comps without a spot price within 7 days of the sale are left out of the premium.
 *
 * Usage:
 *   node scripts/bar-premiums.js [--metals-history FILE] [--terapeak-dir DIR]
 *        [--out FILE] [--min-sample N] [--all] [--stdout]
 *   --all      scan every CSV instead of only bar-named datasets
 *   --stdout   print the report instead of writing --out
 *   --lines    print words and pairs that recur in each maker's titles and are not a
 *              catalogued series, to check a line name against sold titles before adding it
 */
'use strict';

const fs = require('fs');
const path = require('path');
const { parseCSV } = require('../src/services/terapeakService');
const { buildBarPremiumReport, buildLineCandidates } = require('../src/utils/barPremiumStats');

const ROOT = path.resolve(__dirname, '..');
const DEFAULT_DIR = path.join(ROOT, 'data', 'terapeak');
const DEFAULT_OUT = path.join(ROOT, 'data', 'bar-premiums.json');
const VERSION = 1;

const BAR_DATASET_RE = /(^|_)(bar|bars|ingot)(_|\.csv$)|pamp|geiger|valcambi|scottsdale|sunshine|asahi|engelhard|johnson_matthey|heraeus|credit_suisse|silvertowne|metalor|umicore|apmex/i;

function isBarDataset(file) {
  return /\.csv$/i.test(file) && BAR_DATASET_RE.test(file);
}

/** Per-dataset counts, merged across datasets by maximum, so a sale present in two datasets counts once. */
function collectComps(dir, { all = false } = {}) {
  const files = fs.readdirSync(dir).filter(f => (all ? /\.csv$/i.test(f) : isBarDataset(f))).sort();
  const merged = new Map();
  for (const file of files) {
    const { comps } = parseCSV(fs.readFileSync(path.join(dir, file), 'utf8'), file);
    const local = new Map();
    for (const c of comps) {
      const day = c.soldDate ? c.soldDate.slice(0, 10) : '';
      const key = c.itemId ? `id:${c.itemId}|${day}|${c.totalUsd}` : `${c.title}|${day}|${c.totalUsd}`;
      const e = local.get(key);
      if (e) e.count++; else local.set(key, { comp: c, count: 1 });
    }
    for (const [key, e] of local) {
      const m = merged.get(key);
      if (!m || e.count > m.count) merged.set(key, e);
    }
  }
  const comps = [];
  for (const { comp, count } of merged.values()) {
    for (let i = 0; i < count; i++) comps.push({ title: comp.title, totalUsd: comp.totalUsd, soldDate: comp.soldDate });
  }
  return { comps, datasets: files.length };
}

function loadSpotHistory(file) {
  if (!file) return null;
  const parsed = JSON.parse(fs.readFileSync(file, 'utf8'));
  if (!parsed || typeof parsed !== 'object' || Array.isArray(parsed)) throw new Error('metals history must be a JSON object keyed by metal symbol');
  const out = {};
  for (const sym of ['XAU', 'XAG', 'XPT', 'XPD']) {
    const days = parsed[sym];
    if (!days || typeof days !== 'object') continue;
    const clean = {};
    for (const [day, price] of Object.entries(days)) {
      if (/^\d{4}-\d{2}-\d{2}$/.test(day) && typeof price === 'number' && Number.isFinite(price) && price > 0) clean[day] = price;
    }
    if (Object.keys(clean).length) out[sym] = clean;
  }
  return Object.keys(out).length ? out : null;
}

function spotSummary(history) {
  if (!history) return null;
  return Object.fromEntries(Object.entries(history).map(([sym, days]) => {
    const dates = Object.keys(days).sort();
    return [sym, { days: dates.length, first: dates[0], last: dates[dates.length - 1] }];
  }));
}

function run({ dir = DEFAULT_DIR, metalsHistory = null, minSample = 10, all = false } = {}) {
  if (!Number.isInteger(minSample) || minSample < 1) throw new Error('minSample must be a positive integer');
  const { comps, datasets } = collectComps(dir, { all });
  const spotHistory = loadSpotHistory(metalsHistory);
  const report = buildBarPremiumReport(comps, { spotHistory, minSample });
  return {
    version: VERSION,
    backlog: '#333H',
    note: 'Generated by scripts/bar-premiums.js. premium = (sold price + shipping) / (weight * spot on the sale date) - 1, using spot from at most 3 days before the sale; priceRatio = maker median / generic median within the same month. Prices include shipping.',
    source: { datasets, ...report.source },
    spotHistory: spotSummary(spotHistory),
    spotCoverage: report.spotCoverage,
    minSample,
    segments: report.segments,
    uplift: report.uplift,
  };
}

function parseArgs(argv) {
  const opts = {};
  for (let i = 0; i < argv.length; i++) {
    const a = argv[i];
    const value = () => {
      const v = argv[++i];
      if (v === undefined || v.startsWith('--')) throw new Error(`${a} needs a value`);
      return v;
    };
    if (a === '--metals-history') opts.metalsHistory = value();
    else if (a === '--terapeak-dir') opts.dir = value();
    else if (a === '--out') opts.out = value();
    else if (a === '--min-sample') {
      const n = Number(value());
      if (!Number.isInteger(n) || n < 1) throw new Error('--min-sample must be a positive integer');
      opts.minSample = n;
    }
    else if (a === '--all') opts.all = true;
    else if (a === '--stdout') opts.stdout = true;
    else if (a === '--lines') opts.lines = true;
    else throw new Error(`Unknown argument: ${a}`);
  }
  return opts;
}

function main() {
  const { out = DEFAULT_OUT, stdout = false, lines = false, ...runOpts } = parseArgs(process.argv.slice(2));
  if (lines) {
    const { comps } = collectComps(runOpts.dir || DEFAULT_DIR, { all: runOpts.all });
    for (const { brand, candidates } of buildLineCandidates(comps)) {
      console.log(`${brand}: ${candidates.map(c => `${c.phrase} (${c.count})`).join(', ')}`);
    }
    return;
  }
  const report = run(runOpts);
  const text = JSON.stringify(report, null, 2) + '\n';
  if (stdout) process.stdout.write(text);
  else {
    fs.writeFileSync(out, text);
    console.log(`Wrote ${path.relative(ROOT, out)}: ${report.segments.length} segments, ${report.uplift.length} uplift rows, ${report.source.classified} of ${report.source.comps} comps classified.`);
  }
}

if (require.main === module) main();

module.exports = { run, collectComps, isBarDataset, loadSpotHistory, parseArgs, VERSION };
